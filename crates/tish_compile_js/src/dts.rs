//! TypeScript declarations (`.d.ts`) for an ES module built from Tish (`tish build --target js
//! --format esm --types`), so a TypeScript project can import a Tish library with its types.
//!
//! The declarations come from Tish's own annotations and describe the JS the module compiles to:
//!
//! - `T?` (Tish's `T | null`) stays `T | null`; Tish's sized numbers (`i32`, `f64`, …) are `number`;
//!   `bool` is `boolean`; anything unannotated is `any`.
//! - A function whose own body awaits is `async` in JS (see `docs/js-target.md`), so it returns
//!   `Promise<R>`.
//! - Every top-level function, binding and type alias is declared (types an export mentions may be
//!   private to the module); `export` marks the ones the module exports.

use std::sync::Arc;

use tishlang_ast::{
    ExportDeclaration, FunParam, ImportSpecifier, Program, Statement, TypeAnnotation, TypeLiteral,
    TypedParam,
};

use crate::CompileError;

/// Declarations for one module. `import_spec` maps a Tish import specifier to the one the emitted
/// `.js` uses (the same rewrite as the module's own imports), or `None` for a built-in module whose
/// bindings have no declaration file.
pub(crate) fn module_declarations(
    program: &Program,
    import_spec: &mut dyn FnMut(&str) -> Result<Option<String>, CompileError>,
) -> Result<String, CompileError> {
    let mut out = String::from("// Generated by tishlang_compile_js from Tish type annotations\n");
    for stmt in &program.statements {
        match stmt {
            Statement::Import { specifiers, from, .. } => {
                if let Some(spec) = import_spec(from)? {
                    out.push_str(&import_line(specifiers, &spec));
                }
            }
            Statement::Export { declaration, .. } => match declaration.as_ref() {
                ExportDeclaration::Named(inner) => out.push_str(&declare(inner, true)),
                ExportDeclaration::Default(_) => {
                    out.push_str("declare const _default: any;\nexport default _default;\n")
                }
                ExportDeclaration::ReExport { specifiers, all, from, .. } => {
                    let names = export_list(specifiers);
                    match from {
                        Some(from) => {
                            if let Some(spec) = import_spec(from)? {
                                if *all {
                                    out.push_str(&format!("export * from \"{}\";\n", spec));
                                } else {
                                    out.push_str(&format!("export {{ {} }} from \"{}\";\n", names, spec));
                                }
                            }
                        }
                        None => out.push_str(&format!("export {{ {} }};\n", names)),
                    }
                }
            },
            other => out.push_str(&declare(other, false)),
        }
    }
    out.push_str("export {};\n");
    Ok(out)
}

fn import_line(specifiers: &[ImportSpecifier], spec: &str) -> String {
    let mut named = Vec::new();
    let mut lines = String::new();
    for s in specifiers {
        match s {
            ImportSpecifier::Named { name, alias, .. } => named.push(match alias {
                Some(a) => format!("{} as {}", name, a),
                None => name.to_string(),
            }),
            ImportSpecifier::Namespace { name, .. } => {
                lines.push_str(&format!("import * as {} from \"{}\";\n", name, spec))
            }
            ImportSpecifier::Default { name, .. } => {
                lines.push_str(&format!("import {} from \"{}\";\n", name, spec))
            }
        }
    }
    if !named.is_empty() {
        lines.push_str(&format!("import {{ {} }} from \"{}\";\n", named.join(", "), spec));
    }
    lines
}

fn export_list(specifiers: &[ImportSpecifier]) -> String {
    specifiers
        .iter()
        .filter_map(|s| match s {
            ImportSpecifier::Named { name, alias: Some(a), .. } => Some(format!("{} as {}", name, a)),
            ImportSpecifier::Named { name, alias: None, .. } => Some(name.to_string()),
            _ => None,
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// One top-level statement as declarations (empty for statements that declare nothing).
fn declare(stmt: &Statement, exported: bool) -> String {
    let export = if exported { "export " } else { "" };
    match stmt {
        Statement::FunDecl { async_, name, params, rest_param, return_type, body, .. } => {
            let awaits = *async_ || tishlang_ast::stmt_awaits(body, false);
            function(export, name, params, rest_param.as_ref(), return_type.as_ref(), awaits)
        }
        Statement::DeclareFun { async_, name, params, rest_param, return_type, .. } => {
            function(export, name, params, rest_param.as_ref(), return_type.as_ref(), *async_)
        }
        Statement::VarDecl { name, mutable, type_ann, .. } => {
            let kind = if *mutable { "let" } else { "const" };
            format!("{}declare {} {}: {};\n", export, kind, name, ts_type_or_any(type_ann.as_ref()))
        }
        Statement::TypeAlias { name, ty, .. } => {
            format!("{}type {} = {};\n", export, name, ts_type(ty))
        }
        Statement::Multi { statements, .. } => {
            statements.iter().map(|s| declare(s, exported)).collect()
        }
        _ => String::new(),
    }
}

fn function(
    export: &str,
    name: &Arc<str>,
    params: &[FunParam],
    rest: Option<&TypedParam>,
    returns: Option<&TypeAnnotation>,
    awaits: bool,
) -> String {
    let mut parts: Vec<String> = params
        .iter()
        .enumerate()
        .map(|(i, p)| match p {
            FunParam::Simple(tp) => {
                let optional = if tp.default.is_some() { "?" } else { "" };
                format!("{}{}: {}", tp.name, optional, ts_type_or_any(tp.type_ann.as_ref()))
            }
            FunParam::Destructure { type_ann, default, .. } => {
                let optional = if default.is_some() { "?" } else { "" };
                format!("arg{}{}: {}", i, optional, ts_type_or_any(type_ann.as_ref()))
            }
        })
        .collect();
    if let Some(r) = rest {
        let ty = match &r.type_ann {
            Some(t @ TypeAnnotation::Array(_)) => ts_type(t),
            Some(t) => format!("{}[]", wrap(t)),
            None => "any[]".into(),
        };
        parts.push(format!("...{}: {}", r.name, ty));
    }
    let ret = ts_type_or_any(returns);
    let ret = if awaits { format!("Promise<{}>", ret) } else { ret };
    format!("{}declare function {}({}): {};\n", export, name, parts.join(", "), ret)
}

fn ts_type_or_any(t: Option<&TypeAnnotation>) -> String {
    t.map(ts_type).unwrap_or_else(|| "any".into())
}

fn ts_type(t: &TypeAnnotation) -> String {
    match t {
        TypeAnnotation::Simple(name, _) => match name.as_ref() {
            "bool" => "boolean".into(),
            "i8" | "i16" | "i32" | "i64" | "u8" | "u16" | "u32" | "u64" | "f32" | "f64" | "int"
            | "float" => "number".into(),
            other => other.into(),
        },
        TypeAnnotation::Array(inner) => format!("{}[]", wrap(inner)),
        TypeAnnotation::Object(fields) => {
            if fields.is_empty() {
                return "{}".into();
            }
            let body: Vec<String> = fields
                .iter()
                .map(|(k, v)| format!("{}: {}", property_name(k), ts_type(v)))
                .collect();
            format!("{{ {} }}", body.join("; "))
        }
        TypeAnnotation::Function { params, returns } => {
            let ps: Vec<String> =
                params.iter().enumerate().map(|(i, p)| format!("arg{}: {}", i, ts_type(p))).collect();
            format!("({}) => {}", ps.join(", "), ts_type(returns))
        }
        TypeAnnotation::Union(items) => items.iter().map(wrap).collect::<Vec<_>>().join(" | "),
        TypeAnnotation::Intersection(items) => items.iter().map(wrap).collect::<Vec<_>>().join(" & "),
        TypeAnnotation::Tuple(items) => {
            format!("[{}]", items.iter().map(ts_type).collect::<Vec<_>>().join(", "))
        }
        TypeAnnotation::Literal(lit) => match lit {
            TypeLiteral::Str(s) => format!("{:?}", s.as_ref()),
            TypeLiteral::Num(n) => format!("{}", n),
            TypeLiteral::Bool(b) => b.to_string(),
        },
    }
}

/// A type that needs parentheses inside `T[]`, a union or an intersection.
fn wrap(t: &TypeAnnotation) -> String {
    match t {
        TypeAnnotation::Function { .. }
        | TypeAnnotation::Union(_)
        | TypeAnnotation::Intersection(_) => format!("({})", ts_type(t)),
        _ => ts_type(t),
    }
}

fn property_name(k: &str) -> String {
    let plain = k.chars().next().is_some_and(|c| c.is_alphabetic() || c == '_' || c == '$')
        && k.chars().all(|c| c.is_alphanumeric() || c == '_' || c == '$');
    if plain { k.to_string() } else { format!("{:?}", k) }
}

#[cfg(test)]
mod tests {
    use crate::compile_project_esm;

    #[test]
    fn declarations_follow_tish_annotations() {
        let tmp = tempfile::tempdir().expect("tempdir");
        let dir = tmp.path();
        std::fs::write(
            dir.join("session.tish"),
            "export type Status = \"running\" | \"done\"\n\
             export type Session = { id: string, summary: string?, rounds: i32, tags: string[] }\n\
             export fn newSession(id: string, label: string = \"x\"): Session { return { id: id, summary: null, rounds: 0, tags: [] } }\n",
        )
        .unwrap();
        std::fs::write(
            dir.join("main.tish"),
            "import { delay } from \"tish:timers\"\n\
             import { newSession, Session } from \"./session.tish\"\n\
             type Private = { n: number }\n\
             export fn untyped(a, b) { return a }\n\
             export fn wait(s: Session, ms: number): bool { await delay(ms)\n return true }\n\
             export fn sum(...xs: number[]): number { return 0 }\n\
             export fn use(p: Private, f: (number) => string): void {}\n\
             export const LIMIT: number = 4\n\
             export { newSession }\n",
        )
        .unwrap();
        let modules = compile_project_esm(&dir.join("main.tish"), Some(dir), false, "lattish").unwrap();
        let dts = |name: &str| {
            modules.iter().find(|m| m.relative_path.ends_with(name)).map(|m| m.dts.clone()).unwrap()
        };
        let session = dts("session.js");
        assert!(session.contains("export type Status = \"running\" | \"done\";"), "{session}");
        assert!(
            session.contains("export type Session = { id: string; summary: string | null; rounds: number; tags: string[] };"),
            "{session}"
        );
        assert!(session.contains("export declare function newSession(id: string, label?: string): Session;"), "{session}");
        let main = dts("main.js");
        assert!(main.contains("import { newSession, Session } from \"./session.js\";"), "{main}");
        assert!(!main.contains("tish:timers"), "{main}");
        assert!(main.contains("type Private = { n: number };"), "{main}");
        assert!(main.contains("export declare function untyped(a: any, b: any): any;"), "{main}");
        assert!(main.contains("export declare function wait(s: Session, ms: number): Promise<boolean>;"), "{main}");
        assert!(main.contains("export declare function sum(...xs: number[]): number;"), "{main}");
        assert!(main.contains("export declare function use(p: Private, f: (arg0: number) => string): void;"), "{main}");
        assert!(main.contains("export declare const LIMIT: number;"), "{main}");
        assert!(main.contains("export { newSession };"), "{main}");
    }
}
